/** Every line once, in a stable order (the bank renders them in this order). */
export function allCrewLines(): CrewLine[] {
  const out: CrewLine[] = [];
  for (const exchange of CREW_EXCHANGES) out.push(exchange.ask, exchange.answer);
  out.push(...CREW_SOLOS, ...CREW_ACKS);
  return out;
}
